/**
 * Извлекает timestamp из блока сообщения
 * @param DOMElement $node
 * @param DOMXPath $xpath
 * @return int|null
 */
function extractTimestampFromMessage($node, $xpath) {
    $dateNode = $xpath->query('.//div[contains(@class, "date") and contains(@class, "details")]', $node)->item(0);
    if (!$dateNode) return null;

    $title = $dateNode->getAttribute('title');
    if ($title && preg_match('/(\d{2})\.(\d{2})\.(\d{4})/', $title, $matches)) {
        $timestamp = strtotime($matches[3] . '-' . $matches[2] . '-' . $matches[1]);
        if ($timestamp !== false) return $timestamp;
    }

    $dateText = trim($dateNode->textContent);
    $timestamp = strtotime($dateText);
    if ($timestamp !== false) return $timestamp;

    return null;
}

/**
 * Форматирует timestamp в русскую дату (день месяц год)
 * @param int $timestamp
 * @return string
 */
function formatDate($timestamp) {
    $months = [
        1 => 'января', 2 => 'февраля', 3 => 'марта', 4 => 'апреля',
        5 => 'мая', 6 => 'июня', 7 => 'июля', 8 => 'августа',
        9 => 'сентября', 10 => 'октября', 11 => 'ноября', 12 => 'декабря'
    ];
    return date('j', $timestamp) . ' ' . $months[(int)date('n', $timestamp)] . ' ' . date('Y', $timestamp);
}

/**
 * Парсит файл messages.html и возвращает массив сообщений
 * @param string $filePath
 * @return array
 */
function extractMessagesFromHtml($filePath) {
    if (!file_exists($filePath)) {
        echo "Файл $filePath не найден.\n";
        return [];
    }
    $html = file_get_contents($filePath);
    if ($html === false) {
        echo "Не удалось прочитать файл $filePath.\n";
        return [];
    }

    $dom = new DOMDocument();
    libxml_use_internal_errors(true);
    $dom->loadHTML(mb_convert_encoding($html, 'HTML-ENTITIES', 'UTF-8'));
    libxml_clear_errors();

    $xpath = new DOMXPath($dom);
    $messageNodes = $xpath->query('//div[contains(@class, "message")]');
    echo "Найдено блоков с классом message: " . $messageNodes->length . "\n";

    $messages = [];

    foreach ($messageNodes as $idx => $node) {
        $classAttr = $node->getAttribute('class');
        if (strpos($classAttr, 'service') !== false) {
            // Служебные сообщения пропускаем
            continue;
        }

        $timestamp = extractTimestampFromMessage($node, $xpath);
        if (!$timestamp) {
            echo "Блок $idx: не удалось извлечь timestamp\n";
            continue;
        }

        $dateFormatted = formatDate($timestamp);

        $textNode = $xpath->query('.//div[contains(@class, "text")]', $node)->item(0);
        $text = '';
        if ($textNode) {
            foreach ($textNode->childNodes as $child) {
                $text .= $dom->saveHTML($child);
            }
            $text = html_entity_decode($text, ENT_QUOTES | ENT_HTML5, 'UTF-8');
            // Корректируем пути к картинкам, если нужно
            $text = preg_replace('/src="media\//', 'src="blog/media/', $text);
            $text = preg_replace("/src='media\//", "src='blog/media/", $text);
        }

        if ($text) {
            $messages[] = [
                'date' => $dateFormatted,
                'timestamp' => $timestamp,
                'text' => $text,
            ];
        } else {
            echo "Блок $idx: нет текста\n";
        }
    }
    return $messages;
}

